#!/usr/bin/env node
/**
 * Concatenates supabase/migrations/*.sql into supabase/schema.sql — one file
 * to paste into the Supabase SQL editor on a fresh project.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "supabase", "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

const header = `-- =============================================================================
-- Our Story — complete database schema
--
-- Generated by scripts/bundle-schema.mjs from supabase/migrations. Do not edit;
-- change the migrations and run \`npm run db:bundle\`.
--
-- Run ONCE, in the Supabase SQL editor, on a project that does not have these
-- tables yet. The whole script runs in a single transaction: if anything fails,
-- nothing is applied.
-- =============================================================================

begin;
`;

const body = files
  .map((file) => `\n-- >>> ${file}\n\n${readFileSync(join(dir, file), "utf8").trim()}\n`)
  .join("");

writeFileSync(join(root, "supabase", "schema.sql"), `${header}${body}\ncommit;\n`);
console.log(`Wrote supabase/schema.sql from ${files.length} migrations`);
