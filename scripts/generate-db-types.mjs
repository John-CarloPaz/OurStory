#!/usr/bin/env node
/**
 * Generates src/lib/database.types.ts in the same shape as `supabase gen types`,
 * without Docker: builds a scratch database from tests/db/supabase-shim.sql +
 * supabase/migrations/*.sql on a local Postgres and introspects it.
 *
 *   TEST_DATABASE_URL=postgres://postgres@localhost:54329/postgres npm run db:types
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import pg from "pg";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ADMIN_URL = process.env.TEST_DATABASE_URL ?? "postgres://postgres@localhost:54329/postgres";
const OUT = join(ROOT, "src", "lib", "database.types.ts");

const TS_TYPES = {
  uuid: "string",
  text: "string",
  varchar: "string",
  citext: "string",
  date: "string",
  timestamptz: "string",
  timestamp: "string",
  time: "string",
  int2: "number",
  int4: "number",
  int8: "number",
  float4: "number",
  float8: "number",
  numeric: "number",
  bool: "boolean",
  json: "Json",
  jsonb: "Json",
  void: "undefined",
  // format_type() spellings used for function signatures
  "timestamp with time zone": "string",
  "double precision": "number",
  integer: "number",
  bigint: "number",
  boolean: "boolean",
};

const tsType = (udt) => {
  if (udt.startsWith("_")) return `${tsType(udt.slice(1))}[]`;
  if (udt.endsWith("[]")) return `${tsType(udt.slice(0, -2))}[]`;
  return TS_TYPES[udt] ?? "unknown";
};

const dbName = `our_story_types_${Date.now()}`;
const admin = new pg.Client({ connectionString: ADMIN_URL });
await admin.connect();
await admin.query(`create database ${dbName}`);

const url = new URL(ADMIN_URL);
url.pathname = `/${dbName}`;
const client = new pg.Client({ connectionString: url.toString() });

try {
  await client.connect();
  const shim = readFileSync(join(ROOT, "tests", "db", "supabase-shim.sql"), "utf8").replace(
    /create role (\w+) ([^;]+);/g,
    (_m, role, rest) =>
      `do $$ begin if not exists (select 1 from pg_roles where rolname = '${role}') then create role ${role} ${rest}; end if; end $$;`,
  );
  await client.query(shim);
  const migrationsDir = join(ROOT, "supabase", "migrations");
  for (const file of readdirSync(migrationsDir).filter((f) => f.endsWith(".sql")).sort()) {
    await client.query(readFileSync(join(migrationsDir, file), "utf8"));
  }

  const { rows: columns } = await client.query(`
    select c.table_name, c.column_name, c.udt_name, c.is_nullable = 'YES' as nullable,
           c.column_default is not null or c.is_identity = 'YES' as has_default
      from information_schema.columns c
      join information_schema.tables t
        on t.table_schema = c.table_schema and t.table_name = c.table_name and t.table_type = 'BASE TABLE'
     where c.table_schema = 'public'
     order by c.table_name, c.ordinal_position`);

  const { rows: fks } = await client.query(`
    select con.conname as name, rel.relname as table_name, frel.relname as ref_table,
           array(select a.attname from unnest(con.conkey) with ordinality k(n, o)
                 join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.n order by k.o)::text[] as columns,
           array(select a.attname from unnest(con.confkey) with ordinality k(n, o)
                 join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.n order by k.o)::text[] as ref_columns,
           exists (
             select 1 from pg_constraint u
              where u.conrelid = con.conrelid and u.contype in ('p', 'u')
                and (select array_agg(x order by x) from unnest(u.conkey) x) = (select array_agg(x order by x) from unnest(con.conkey) x)
           ) as one_to_one
      from pg_constraint con
      join pg_class rel on rel.oid = con.conrelid
      join pg_namespace n on n.oid = rel.relnamespace
      join pg_class frel on frel.oid = con.confrelid
      join pg_namespace fn on fn.oid = frel.relnamespace
     where con.contype = 'f' and n.nspname = 'public' and fn.nspname = 'public'
     order by rel.relname, con.conname`);

  const { rows: functions } = await client.query(`
    select p.proname as name,
           coalesce(p.proargnames, '{}')::text[] as arg_names,
           array(select format_type(t, null) from unnest(p.proargtypes) t)::text[] as arg_types,
           p.pronargdefaults as n_defaults,
           format_type(p.prorettype, null) as return_type
      from pg_proc p
      join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public' and p.prokind = 'f'
     order by p.proname`);

  const tables = new Map();
  for (const col of columns) {
    if (!tables.has(col.table_name)) tables.set(col.table_name, []);
    tables.get(col.table_name).push(col);
  }

  const indent = (n) => " ".repeat(n);
  let out = `// Generated by scripts/generate-db-types.mjs from supabase/migrations. Do not edit.\n\n`;
  out += `export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\n`;
  out += `export type Database = {\n  __InternalSupabase: { PostgrestVersion: "13" };\n  public: {\n    Tables: {\n`;

  for (const [table, cols] of tables) {
    const field = (c, mode) => {
      const type = `${tsType(c.udt_name)}${c.nullable ? " | null" : ""}`;
      const optional = mode === "Update" || (mode === "Insert" && (c.nullable || c.has_default));
      return `${indent(10)}${c.column_name}${optional ? "?" : ""}: ${type};\n`;
    };
    out += `${indent(6)}${table}: {\n`;
    for (const mode of ["Row", "Insert", "Update"]) {
      out += `${indent(8)}${mode}: {\n${cols.map((c) => field(c, mode)).join("")}${indent(8)}};\n`;
    }
    out += `${indent(8)}Relationships: [\n`;
    for (const fk of fks.filter((f) => f.table_name === table)) {
      out += `${indent(10)}{\n`;
      out += `${indent(12)}foreignKeyName: "${fk.name}";\n`;
      out += `${indent(12)}columns: [${fk.columns.map((c) => `"${c}"`).join(", ")}];\n`;
      out += `${indent(12)}isOneToOne: ${fk.one_to_one};\n`;
      out += `${indent(12)}referencedRelation: "${fk.ref_table}";\n`;
      out += `${indent(12)}referencedColumns: [${fk.ref_columns.map((c) => `"${c}"`).join(", ")}];\n`;
      out += `${indent(10)}},\n`;
    }
    out += `${indent(8)}];\n${indent(6)}};\n`;
  }

  out += `    };\n    Views: { [_ in never]: never };\n    Functions: {\n`;
  for (const fn of functions) {
    const firstOptional = fn.arg_types.length - fn.n_defaults;
    const args = fn.arg_types
      .map((t, i) => `${fn.arg_names[i]}${i >= firstOptional ? "?" : ""}: ${tsType(t)}`)
      .join("; ");
    out += `${indent(6)}${fn.name}: { Args: { ${args} }; Returns: ${tsType(fn.return_type)} };\n`;
  }
  out += `    };\n    Enums: { [_ in never]: never };\n    CompositeTypes: { [_ in never]: never };\n  };\n};\n\n`;
  out += `type PublicSchema = Database["public"];\n`;
  out += `export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];\n`;
  out += `export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];\n`;
  out += `export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];\n`;

  writeFileSync(OUT, out);
  console.log(`Wrote ${OUT} (${tables.size} tables, ${functions.length} functions)`);
} finally {
  await client.end();
  await admin.query(`drop database if exists ${dbName} with (force)`);
  await admin.end();
}
